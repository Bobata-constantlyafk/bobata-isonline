// One-time tool: reads the six existing app/content/articles/*.mdx files
// and emits migrations/0003_seed_articles.sql, so the initial D1 data
// matches the hand-written files exactly instead of being retyped by hand
// into SQL (and risking a quoting mistake in the process).
//
// Not part of the build — run once, review the output, commit it as a
// migration. Safe to delete after that migration is applied everywhere.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import matter from "gray-matter";

const contentDir = fileURLToPath(
  new URL("../app/content/articles", import.meta.url),
);
const outFile = fileURLToPath(
  new URL("../migrations/0003_seed_articles.sql", import.meta.url),
);

function sqlString(value) {
  if (value === undefined || value === null) return "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
}

const files = readdirSync(contentDir).filter((f) => f.endsWith(".mdx"));
const lines = [
  "-- Migration number: 0003 \t" + new Date().toISOString(),
  "",
  "-- Generated by scripts/generate-seed-sql.mjs from the six hand-written",
  "-- MDX files that were the source of truth before this migration.",
  "",
];

for (const file of files.sort()) {
  const slug = file.replace(/\.mdx$/, "");
  const raw = readFileSync(`${contentDir}/${file}`, "utf8");
  const { data: fm, content } = matter(raw);
  const body = content.trim();

  const cols = [
    "slug",
    "title",
    "skin",
    "type",
    "sort_order",
    "date",
    "kicker",
    "badge",
    "excerpt",
    "blog_kicker",
    "blog_background",
    "blog_tint",
    "body",
  ];
  const vals = [
    sqlString(slug),
    sqlString(fm.title),
    sqlString(fm.skin),
    sqlString(fm.type),
    Number(fm.order),
    sqlString(fm.date),
    sqlString(fm.kicker),
    sqlString(fm.badge),
    sqlString(fm.excerpt),
    sqlString(fm.blogKicker),
    sqlString(fm.blogBackground),
    sqlString(fm.blogTint),
    fm.type === "essay" ? sqlString(body) : "NULL",
  ];
  lines.push(
    `INSERT INTO articles (${cols.join(", ")}) VALUES (${vals.join(", ")});`,
  );

  if (fm.type === "list" && Array.isArray(fm.items)) {
    fm.items.forEach((item, i) => {
      lines.push(
        `INSERT INTO article_items (article_id, position, title, meta) VALUES ` +
          `((SELECT id FROM articles WHERE slug = ${sqlString(slug)}), ${i + 1}, ${sqlString(item.title)}, ${sqlString(item.meta)});`,
      );
    });
  }
  lines.push("");
}

writeFileSync(outFile, lines.join("\n"));
console.log(`Wrote ${outFile} (${files.length} articles)`);
